DONE, DONE_VALUE = RES + 0x7F, 0xA5
CPU_HZ, I2C_HZ = 27000000, 400000

def exe(n):
    p = os.path.join(bin_dir, n)
    return p + ".exe" if os.name == "nt" or (not os.path.exists(p) and os.path.exists(p + ".exe")) else p
win_from_wsl = os.name != "nt" and exe("asmc").endswith(".exe")
def arg(path):
    return subprocess.run(["wslpath", "-w", path], capture_output=True, text=True).stdout.strip() if win_from_wsl else path
def run(cmd):
    r = subprocess.run(cmd, capture_output=True)
    d = lambda b: b.decode("utf-8", errors="replace") if b else ""
    return r.returncode, d(r.stdout) + d(r.stderr)
def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8", newline="\n").write(text)

# ---- the planning formulas of spec 14.3 / 14.4 (what one instruction takes to EXECUTE; written here, not taken from the simulator) ----------
def i2c_cycles(phases): return math.ceil(9 * phases * CPU_HZ / I2C_HZ)
def xfer_read(addr_len, n): return 2 + i2c_cycles((1 + addr_len if addr_len else 0) + 1 + n)
def xfer_write(addr_len, n): return 2 + i2c_cycles(1 + addr_len + n)

class T:
    def __init__(self, name, title, zh):
        self.name, self.title, self.zh = name, title, zh
        self.main, self.peri, self.head = [], [], []
        self.items = []          # (key, zh, domain, marker0, n1, n2, exec_cycles or None, formula zh, parameters)
        self.board = False
        self.env = ""
        self.next_marker = {"main": 0, "peri": 16}
        self.done_by = "main"
    def code(self, dom): return self.main if dom == "main" else self.peri
    def mark(self, dom):
        k = self.next_marker[dom]
        self.next_marker[dom] += 1
        self.code(dom).append("    EXEC_CSR WRITE8 RES + %d, 0x%02X            ; marker %d" % (k, 0x40 + k, k))
        return k
    def measure(self, dom, key, zh, lines_for, n1, n2, exec_cycles, formula, params, between=None):
        """marker, n1 x the instruction, marker, n2 x the instruction, marker. `lines_for(i)` gives the lines of repetition i."""
        m0 = self.mark(dom)
        for i in range(n1): self.code(dom).extend(lines_for(i))
        self.mark(dom)
        if between: self.code(dom).extend(between)
        for i in range(n1, n1 + n2): self.code(dom).extend(lines_for(i))
        self.mark(dom)
        self.items.append((key, zh, dom, m0, n1, n2, exec_cycles, formula, params))
    def source(self):
        s = ("; %s -- %s\n; Layer-3 timing program (generated by conformance/make_timing.py: edit that, not this file).\n"
             "; Markers are CSR writes to RES + k; the intervals between them are what is measured. Predictions: TIMING.md\n"
             '.include "conf_defs.inc"\n' % (self.name, self.title))
        if self.board: s += '.include "conf_board.inc"                      ; the CSRs of the board: put YOUR addresses and bits there first\n'
        s += "\n".join(self.head) + ("\n" if self.head else "")
        if self.main:
            s += ".main\n.assume MAIN_SCRATCHPAD[0..31] defined\n" + "\n".join(self.main) + "\n"
            if self.done_by == "main": s += "    EXEC_CSR WRITE8 RES_DONE, 0x%02X\ndone:\n    JMP done\n" % DONE_VALUE
            else: s += "mhalt:\n    JMP mhalt\n"
        if self.peri:
            s += ".peri\n.assume PERI_RX_BUF[0..31] defined\n" + "\n".join(self.peri) + "\n"
            if self.done_by == "peri": s += "    EXEC_CSR WRITE8 RES_DONE, 0x%02X\npdone:\n    JMP pdone\n" % DONE_VALUE
            else: s += "phalt:\n    JMP phalt\n"
        return s

