#!/usr/bin/env python3
"""Layer-3 timing kit: does an instruction take as many cycles on the hardware as in the model?

Unlike layers 1 and 2 there is no right answer to check against: the cycle counts are PLANNING values that the RTL is to supply. So this kit is for
MEASURING. Each program brackets N repetitions of one instruction between two marker writes (a CSR write to RES + k), twice, with two different N:

    marker k,  N1 x instruction,  marker k+1,  N2 x instruction,  marker k+2

    one instruction = ((t[k+2] - t[k+1]) - (t[k+1] - t[k])) / (N2 - N1)        (the markers' own time cancels)

The table TIMING.md gives what the MODEL predicts for every interval -- with the default parameters, or with yours (--params) -- and how each
per-instruction time splits into fetching and executing. Measure the same intervals on the FPGA / in the RTL simulation, put them into a CSV
(timing_measured_template.csv shows the form) and run  --measured FILE : the report sets measurement beside prediction and says what the
measurement implies for the parameters.

usage: make_timing.py [--bin-dir DIR] [--out DIR] [--res-base 0x600] [--params FILE] [--measured FILE] [--check]
    --params FILE     predict with these hardware parameters (a .simparams file) instead of the initial values
    --measured FILE   compare measured intervals with the prediction (CSV: test,from_marker,to_marker,cycles)
    --check           self-test (ctest timing_kit): the programs assemble and run, and with fetching switched off every per-instruction time equals
                      the planning formula of spec 14.3 / 14.4
"""
import csv, math, os, subprocess, sys

