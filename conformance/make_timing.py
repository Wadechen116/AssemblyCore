def timer_wait(dom, tag, period):
    if dom == "main":
        return ["    EXEC_CSR WRITE8 MAIN_TPER,   %d & 0xFF" % period, "    EXEC_CSR WRITE8 MAIN_TPER_H, %d >> 8" % period, "MARK",
                "    EXEC_CSR SET8 MAIN_CTRL, MAIN_TIMER_START", "%s:" % tag, "    BR.COND MAIN_TIMER_DONE, %s_d" % tag, "    JMP %s" % tag, "%s_d:" % tag, "MARK"]
    return ["    EXEC_CSR WRITE8 PERI_TPER,   %d & 0xFF" % period, "    EXEC_CSR WRITE8 PERI_TPER_H, %d >> 8" % period, "MARK",
            "    EXEC_CSR SET8 PERI_CTRL, PERI_TIMER_START", "%s:" % tag, "    BR.IF_TIMER_DONE %s_d" % tag, "    JMP %s" % tag, "%s_d:" % tag, "MARK"]
