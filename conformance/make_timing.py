def marker_times(t, extra):
    """Run the program in the simulator; the cycle of the first write to each marker address."""
    d = os.path.join(out_dir, t.name)
    os.makedirs(d, exist_ok=True)
    src = os.path.join(here, t.name + ".asm")
    ev = os.path.join(d, t.name + ".events.csv")
    cmd = [exe("asmsim"), arg(src), "-I", arg(here), "--until", "csr[0x%03X] == 0x%02X" % (DONE, DONE_VALUE), "--cycles", "400000000", "--events", arg(ev)] + extra
    envtext = (BOARD_ENV if t.board else "") + t.env
    if envtext:
        envp = os.path.join(d, t.name + "_env.cfg")
        write(envp, envtext)
        cmd += ["--env", arg(envp)]
    if params_file: cmd += ["--params", arg(os.path.abspath(params_file))]
    rc, out = run(cmd)
    times = {}
    if os.path.exists(ev):
        with open(ev, encoding="utf-8", errors="replace", newline="") as f:
            for row in csv.DictReader(f):
                if row["type"] == "csr" and row["what"] == "write" and RES <= int(row["a"]) <= DONE: times.setdefault(int(row["a"]) - RES, int(row["cycle"]))
        os.remove(ev)
    return times, out

def per_instruction(times, m0, n1, n2):
    if any(k not in times for k in (m0, m0 + 1, m0 + 2)): return None, None, None
    a, b = times[m0 + 1] - times[m0], times[m0 + 2] - times[m0 + 1]
    return a, b, (b - a) / (n2 - n1)

failures = 0
for t in tests:
    src_text = t.source()
    if getattr(t, "no_halt_peri", False): src_text = src_text.replace("phalt:\n    JMP phalt\n", "")
    path = os.path.join(here, t.name + ".asm")
    if check_only:
        if (open(path, encoding="utf-8").read() if os.path.exists(path) else "") != src_text:
            print("  FAIL  %s.asm is not what the generator writes (run make_timing.py)" % t.name); failures += 1
    else: write(path, src_text)
    d = os.path.join(out_dir, t.name)
    os.makedirs(d, exist_ok=True)
    rc, out = run([exe("asmc"), arg(path), "-I", arg(here), "-o", arg(os.path.join(d, t.name)), "--list", "--hex", "--artifacts", "--eeprom",
                   "--no-warn", "W504", "--no-warn", "W510", "--no-warn", "W402", "--no-warn", "W503", "--no-warn", "W502"])
    if rc != 0:
        print("  FAIL  %s does not assemble\n%s" % (t.name, out)); failures += 1

results = {}                      # (test, mode) -> marker times
for t in tests:
    for mode, _, extra in MODES:
        times, out = marker_times(t, extra)
        results[(t.name, mode)] = times
        if 0x7F not in times:
            print("  FAIL  %s (%s): did not reach its end\n%s" % (t.name, mode, out[-300:])); failures += 1

# ---- self-test: with fetching switched off, one instruction takes what the planning formula of the spec says ------------------------------------
if not params_file:
    for t in tests:
        tm = results[(t.name, "no_fetch")]
        for key, zh, dom, m0, n1, n2, ex, formula, params in t.items:
            a, b, per = per_instruction(tm, m0, n1, n2)
            if ex is None: continue
            if per is None or abs(per - ex) > 1e-9:
                print("  FAIL  %s %s: %s cycles per instruction, the spec's planning formula gives %s" % (t.name, key, per, ex)); failures += 1
            else: print("  PASS  %-10s %-22s %6g cycles = %s" % (t.name, key, per, formula))
        for dom, marks in getattr(t, "timer_rows", []):
            if all(k in tm for k in marks):
                tick = ((tm[marks[3]] - tm[marks[2]]) - (tm[marks[1]] - tm[marks[0]])) / (P2 - P1)
                ok = abs(tick - 2.0) < 0.01
                print("  %s  %-10s %-22s %.4f cycles per tick (13.5 MHz at 27 MHz is 2)" % ("PASS" if ok else "FAIL", t.name, dom + "_timer_tick", tick))
                if not ok: failures += 1
            else: print("  FAIL  %s: the %s timer markers are missing" % (t.name, dom)); failures += 1
    # the model itself: a contended CSR write is never faster than an uncontended one
    alone = per_instruction(results[("t04_csr", "no_fetch")], 0, 4, 12)[2]
    cont = per_instruction(results[("t08_csr_contended", "no_fetch")], 0, 4, 12)[2]
    if alone is None or cont is None or cont < alone: print("  FAIL  t08: a contended CSR write (%s) is faster than one alone (%s)" % (cont, alone)); failures += 1
    else: print("  PASS  %-10s %-22s %6g cycles against %g alone" % ("t08", "csr_write8_contended", cont, alone))

print(("OK" if not failures else "FAILED") + "      %d failure(s)" % failures)
if check_only or failures: sys.exit(1 if failures else 0)

