def sram_patch(text, base_word, off, value):
    """One byte of a logical image in the shared-SRAM word file (logical byte +0 is bits [7:0] of the word)."""
    w, lane = base_word + off // 4, off % 4
    out, hit = [], False
    for line in text.split("\n"):
        m = re.match(r"^([0-9A-Fa-f]{4}) ([0-9A-Fa-f]{8})(.*)$", line)
        if m and int(m.group(1), 16) == w:
            v = int(m.group(2), 16)
            v = (v & ~(0xFF << (8 * lane))) | (value << (8 * lane))
            line = "%s %08X%s" % (m.group(1), v, m.group(3))
            hit = True
        out.append(line)
    return "\n".join(out), hit

