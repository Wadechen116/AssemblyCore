class Case:
    """id: the row of HW_FAULT_DETECTION.md.  dom: which sequencer runs the victim.  victim: its source lines (the FIRST line is the victim unless
    `victim_at` names another).  patch(ctx): the byte changes.  code: the fault the model raises."""
    def __init__(self, id, dom, zh, victim, patch, code, change_zh, pre=(), head=(), after_marker=False, done=False, victim_at=0, note=""):
        self.id, self.dom, self.zh, self.victim, self.patch, self.code, self.change_zh = id, dom, zh, list(victim), patch, code, change_zh
        self.pre, self.head, self.after_marker, self.done, self.victim_at, self.note = list(pre), list(head), after_marker, done, victim_at, note
        self.name = "f_" + id.lower()
    def source(self):
        s = ("; %s -- the carrier of fault case %s (generated by conformance/make_faults.py: edit that, not this file).\n"
             "; This program is LEGAL. The image under test is this one with the bytes changed that FAULTS.md lists for %s.\n"
             '.include "conf_defs.inc"\n' % (self.name, self.id, self.id))
        s += "".join(l + "\n" for l in self.head)
        lines = [".main", ".assume MAIN_SCRATCHPAD[0..31] defined"] if self.dom == "main" else [".peri", ".assume PERI_RX_BUF[0..31] defined"]
        lines += self.pre
        lines.append("    EXEC_CSR WRITE8 RES + 0, 0xF0              ; marker: the next instruction is the one under test")
        self.victim_line = s.count("\n") + len(lines) + 1 + self.victim_at
        self.first_victim_line = s.count("\n") + len(lines) + 1
        lines += self.victim
        lines.append("    EXEC_CSR WRITE8 RES + 1, 0x0F              ; marker: execution went on past it")
        lines.append("    EXEC_CSR WRITE8 RES_DONE, 0x%02X" % DONE_VALUE)
        lines += ["done:", "    JMP done"]
        self.final_jmp_line = s.count("\n") + len(lines)
        return s + "\n".join(lines) + "\n"

class Ctx:
    """The assembled carrier: where things are in the logical image of the victim's domain."""
    def __init__(self, case, d, prefix):
        self.case = case
        dom = "Main" if case.dom == "main" else "Peri"
        desc = json.load(open(prefix + ".descriptors.json", encoding="utf-8"))
        self.tables = {}
        self.by_line = {}
        for dd in desc["domains"]:
            if dd["domain"] != dom: continue
            for t in dd["tables"]:
                self.tables[t["table"]] = t
                for e in t.get("entries", []):
                    for u in e.get("users", []):
                        self.by_line.setdefault(u["line"], []).append((t, e, u["pc"]))
        self.image = bytearray(open(prefix + (".main.bin" if case.dom == "main" else ".peri.bin"), "rb").read())
    def entry(self, line, table_part=None):
        """(offset in the image, bytes, value, pc of the instruction) of the descriptor the instruction at `line` uses."""
        for t, e, pc in self.by_line.get(line, []):
            if table_part and table_part not in t["table"]: continue
            if t["table"] in ("DeviceMap", "MAIN_CONST_POOL"): continue
            return t["offset"] + e["index"] * t["entry_bytes"], t["entry_bytes"], e["value"], pc, e["index"]
        raise KeyError("no descriptor for line %d of %s (%s)" % (line, self.case.name, self.by_line.keys()))
    def victim(self, table_part=None): return self.entry(self.case.victim_line, table_part)
    def set_desc(self, line, new_value, table_part=None):
        off, n, old, pc, _ = self.entry(line, table_part)
        return [(off, [(new_value >> (8 * i)) & 0xFF for i in range(n)])]
    def table(self, part):
        for k, t in self.tables.items():
            if part in k: return t
        raise KeyError(part)

