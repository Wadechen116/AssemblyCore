#!/usr/bin/env python3
"""Layer-4 fault kit: what does the hardware do with an instruction it must not execute?

One image per row of docs/HW_FAULT_DETECTION.md (the rows are named by its ids: M1, B5, V9 ...). The assembler refuses to write an illegal
instruction, so each image is made in two steps: a small LEGAL program is assembled (the carrier), and then one or two bytes of its image are
changed so that one instruction -- the victim -- becomes the illegal thing of that row. The carrier brackets the victim with two marker writes:

    RES + 0 = 0xF0     the next instruction is the victim
    <victim>
    RES + 1 = 0x0F     execution went on past the victim
    RES_DONE = 0xA5    the program ran to its end

In the MODEL the victim faults: RES + 0 is written, RES + 1 and RES_DONE are not, the sequencer stops. On the hardware, look at the same three
writes and at wherever the hardware reports a fault: FAULTS.md has the model's answer for every image and the columns to fill in.

usage: make_faults.py [--bin-dir DIR] [--out DIR] [--res-base 0x600] [--check]
    --check   self-test (ctest fault_kit): every carrier runs clean to its end, and every changed image faults in the simulator with the code the
              table names, at the victim
"""
