// Hardware description (docs/HARDWARE.md): file format, generators, importer, validation, and that what is generated really works.
#include <cstdio>
#include <fstream>
#include <sstream>

#include "asmcore/asmcore.h"
#include "asmcore/hardware.h"
#include "asmcore/sim.h"

using namespace asmcore;

static int g_pass = 0, g_fail = 0;
static void check(bool ok, const std::string& what, const std::string& why = "") {
    if (ok) { g_pass++; std::printf("  PASS  %s\n", what.c_str()); return; }
    g_fail++;
    std::printf("  FAIL  %s\n        %s\n", what.c_str(), why.c_str());
}
static void section(const char* s) { std::printf("\n%s\n", s); }

#ifndef ASMCORE_SOURCE_DIR
#define ASMCORE_SOURCE_DIR "."
#endif
static std::string slurp(const std::string& rel) {
    std::ifstream in(std::string(ASMCORE_SOURCE_DIR) + "/" + rel, std::ios::binary);
    std::ostringstream ss;
    ss << in.rdbuf();
    return ss.str();
}
static std::string join(const std::vector<std::string>& v) { std::string s; for (auto& x : v) s += x + " | "; return s; }
static bool hasProblem(const std::vector<HwProblem>& p, bool error, const std::string& needle) {
    for (auto& x : p) if (x.error == error && (x.message.find(needle) != std::string::npos || x.where.find(needle) != std::string::npos)) return true;
    return false;
}
static std::string show(const std::vector<HwProblem>& p) { std::string s; for (auto& x : p) s += std::string(x.error ? "error " : "warning ") + x.where + ": " + x.message + "\n"; return s; }
static int errorsIn(const std::vector<HwProblem>& p) { int n = 0; for (auto& x : p) n += x.error; return n; }

// a small board by hand
static Hardware board() {
    Hardware hw;
    hw.name = "test board";
    hw.equs.push_back({"PERI_DONE", "0x01", "done bit"});
    HwConst k;
    k.name = "K_A";
    k.width = 2;
    k.values = {"300"};
    hw.consts.push_back(k);
    HwCsr c;
    c.name = "PERI_CTRL";
    c.addr = 0x302;
    c.kind = "action";
    c.bit[0] = "done_set";
    c.bit[3] = "timer_start";
    c.role[3] = "timer_start";
    hw.csrs.push_back(c);
    HwCsr t;
    t.name = "TPER";
    t.addr = 0x310;
    t.kind = "value";
    t.bind = "timer_period";
    t.bytes = 2;
    hw.csrs.push_back(t);
    HwDevice d;
    d.name = "imu";
    d.symbol = "DEV_IMU";
    d.addr = 0x68;
    d.index = 0;
    d.keys = {{"reg 0x3a", "0x00, 0x01"}, {"block 0x43", "0x00 0x0a 0x00 0x14"}};
    hw.devices.push_back(d);
    HwService s;
    s.name = "GYRO";
    s.id = 1;
    s.len = 6;
    s.wire = 'B';
    hw.services.push_back(s);
    HwSection sim;
    sim.kind = "sim";
    sim.kv = {{"unmapped_csr", "ram"}};
    hw.env.push_back(sim);
    return hw;
}

static void t_format() {
    section("the .achw file: write, read, write again");
    Hardware hw = board();
    std::string text = serializeHardware(hw);
    Hardware back;
    std::vector<std::string> errs;
    check(parseHardware(text, back, errs), "what serializeHardware wrote can be read", join(errs));
    check(serializeHardware(back) == text, "...and writing it again gives the same text (deterministic, nothing lost)");
    check(back.csrs.size() == 2 && back.csrs[0].role[3] == "timer_start" && back.csrs[0].bit[3] == "timer_start" && back.csrs[1].bytes == 2 && back.csrs[1].addr == 0x310, "CSR fields, bit actions, bit roles");
    check(back.devices.size() == 1 && back.devices[0].index == 0 && back.devices[0].keys.size() == 2 && back.devices[0].keys[1].first == "block 0x43", "device with its register keys");
    check(back.services[0].wire == 'B' && back.services[0].len == 6 && back.consts[0].width == 2 && back.equs[0].description == "done bit", "service, constant, equ");
    Hardware bad;
    errs.clear();
    check(!parseHardware("[csr X]\naddr = 0x10\nbogus = 1\n[nonsense Y]\n[service S]\nwire = sideways\n", bad, errs) && errs.size() >= 3, "unknown keys, sections and values are reported", join(errs));
    bool lines = true;
    for (auto& e : errs) if (e.find("line ") == std::string::npos) lines = false;
    check(lines, "...each with its line number", join(errs));
}

static void t_generate() {
    section("generated files");
    Hardware hw = board();
    std::string inc = generateInc(hw, "board.achw"), env = generateEnv(hw, "board.achw");
    check(inc.find("Generated by the AssemblyCore Hardware Designer from board.achw") != std::string::npos, "the generated include says where it comes from");
    check(inc.find(".csr PERI_CTRL = 0x302") != std::string::npos && inc.find(".csrbit PERI_CTRL[3] = timer_start") != std::string::npos && inc.find(".service GYRO = 1, len=6, big") != std::string::npos &&
              inc.find(".devmap 0, I2C, 0x68, DEV_IMU") != std::string::npos && inc.find(".const K_A dw 300") != std::string::npos && inc.find(".equ PERI_DONE = 0x01    ; done bit") != std::string::npos,
          "definitions: .csr .csrbit .service .devmap .const .equ", inc);
    check(env.find("[csr PERI_CTRL]") != std::string::npos && env.find("bit3 = timer_start") != std::string::npos && env.find("role3") == std::string::npos && env.find("[device imu]") != std::string::npos &&
              env.find("addr = 0x68") != std::string::npos && env.find("bind = timer_period") != std::string::npos && env.find("bytes = 2") != std::string::npos,
          "environment: [csr] with actions (no assembler-only roles), [device]", env);
    check(generateInc(hw, "board.achw") == inc && generateEnv(hw, "board.achw") == env, "generation is deterministic");
    // it really works with the real tools
    std::vector<HwProblem> tools = checkHardwareWithTools(hw);
    check(errorsIn(tools) == 0, "the assembler and the simulator accept the generated files", show(tools));
    std::vector<Source> src{Source{"board.inc", inc}, Source{"p.asm", ".main\nloop: EXEC_CSR WRITE8 PERI_CTRL, PERI_DONE\n BR.COND PERI_RESULT_VALID, loop, safe\n JMP loop\n.peri\np: EXEC_XFER READ dev=DEV_IMU, len=2, ptr=0, ext=[0x43]\n EXEC_PUB service=GYRO, src=0, len=2\nh: JMP h\n"}};
    Options o;
    Result r = assemble(src, nullptr, o);
    check(r.ok, "a program can use every generated name", r.diagnosticsText());
}

static void t_import() {
    section("importing the sample files");
    std::string inc = slurp("sample/common/defs.inc"), env = slurp("sample/02_imu_gyro/imu_env.cfg");
    check(!inc.empty() && !env.empty(), "sample files found");
    Hardware hw;
    std::vector<std::string> errs;
    check(importHardware(inc, env, hw, errs), "defs.inc + imu_env.cfg import without losing anything", join(errs));
    check(hw.findCsr("PERI_CTRL") && hw.findCsr("PERI_CTRL")->kind == "action" && hw.findCsr("PERI_CTRL")->addr == 0x302 && hw.findCsr("PERI_CTRL")->role[3] == "timer_start" && hw.findCsr("PERI_CTRL")->bit[3] == "timer_start",
          "CSR addresses (from the include), kinds and bit actions (from the environment) and bit roles are merged");
    check(hw.findService("SID_IMU_GYRO_RAW") && hw.findService("SID_IMU_GYRO_RAW")->len == 6 && hw.findService("SID_IMU_GYRO_RAW")->wire == 'B', "the service contract");
    check(hw.findCsr("PERI_TPER_H") && !hw.findCsr("PERI_TPER_H")->simulated && hw.findCsr("PERI_TPER") && hw.findCsr("PERI_TPER")->bytes == 2, "PERI_TPER_H (the second byte of the 2-byte PERI_TPER) stays an assembler name only");
    check(hw.devices.size() == 1 && hw.devices[0].name == "imu" && hw.devices[0].index == 0 && hw.devices[0].symbol == "DEV_IMU" && hw.devices[0].simulated, "the environment device is joined with its DeviceMap entry (same I2C address)");
    std::vector<HwProblem> v = validateHardware(hw);
    check(errorsIn(v) == 0, "the imported description validates", show(v));
    // the generated files replace the originals: the image is byte for byte the same, and the sample scenario still passes
    std::string main = slurp("sample/02_imu_gyro/imu_gyro.asm");
    size_t at = main.find(".include \"defs.inc\"");
    check(at != std::string::npos, "sample source found");
    if (at == std::string::npos) return;
    std::string body = main.substr(0, at) + main.substr(at + std::string(".include \"defs.inc\"").size());
    Options o;
    auto res = [&](const std::string&, const std::string& n, Source& out) { out.name = n; out.text = slurp("sample/common/" + n); return !out.text.empty(); };
    Result orig = assemble({Source{"imu_gyro.asm", main}}, res, o);
    Result gen = assemble({Source{"hardware.inc", generateInc(hw)}, Source{"imu_gyro.asm", body}}, nullptr, o);
    check(orig.ok && gen.ok, "both versions assemble", orig.diagnosticsText() + gen.diagnosticsText());
    check(orig.ok && gen.ok && orig.main.bytes == gen.main.bytes && orig.peri.bytes == gen.peri.bytes, "same Main and Peri images with the generated include as with the hand-written defs.inc");
    check(gen.warningCount() == 0, "and no warnings", gen.diagnosticsText());
    sim::SimConfig cfg;
    cfg.env = generateEnv(hw);
    sim::Simulator sm(gen, cfg);
    check(sm.ok(), "the generated environment loads", sm.configErrors().empty() ? "" : sm.configErrors()[0]);
    sim::ScenarioResult sr = sim::runScenario(sm, slurp("sample/02_imu_gyro/imu_gyro.scn"));
    check(sr.pass && sr.checks >= 8, "the sample scenario passes with the generated environment", join(sr.log));
}

static void t_validate() {
    section("validation: messages for the person filling in the form");
    {
        Hardware hw = board();
        check(errorsIn(validateHardware(hw)) == 0, "the hand-made board is valid");
    }
    {
        Hardware hw = board();
        hw.csrs[1].addr = 0x302;
        check(hasProblem(validateHardware(hw), true, "already taken by csr PERI_CTRL"), "two CSRs at one address");
    }
    {
        Hardware hw = board();
        hw.csrs[1].addr = 0x301;                    // a 2-byte value CSR covers 0x301 and 0x302
        check(hasProblem(validateHardware(hw), true, "0x302 is already taken"), "a multi-byte value CSR claims all its addresses");
    }
    {
        Hardware hw = board();
        hw.services[0].name = "PERI_CTRL";
        check(hasProblem(validateHardware(hw), true, "already used"), "a service with a CSR's name (one shared namespace)");
    }
    {
        Hardware hw = board();
        hw.csrs[0].name = "1BAD";
        check(hasProblem(validateHardware(hw), true, "not a valid name"), "an invalid name");
    }
    {
        Hardware hw = board();
        hw.csrs[0].addr = 0x1000;
        check(hasProblem(validateHardware(hw), true, "0x000..0xFFF"), "a CSR address beyond 12 bits");
    }
    {
        Hardware hw = board();
        hw.csrs[1].bind.clear();
        check(hasProblem(validateHardware(hw), true, "needs 'bind'"), "a value CSR without its signal");
    }
    {
        Hardware hw = board();
        hw.csrs[0].bit[1] = "no_such_action";
        check(hasProblem(validateHardware(hw), true, "unknown action 'no_such_action'"), "an unknown action");
    }
    {
        Hardware hw = board();
        hw.csrs[0].role[3] = "poll_arm";
        check(hasProblem(validateHardware(hw), false, "disagree"), "a role the simulator action contradicts is a warning");
        hw.csrs[0].role[3] = "banana";
        check(hasProblem(validateHardware(hw), true, "role 'banana'"), "an unknown role is an error");
    }
    {
        Hardware hw = board();
        hw.services[0].id = 16;
        check(hasProblem(validateHardware(hw), true, "1..15"), "service id 16");
        hw.services[0].id = 1;
        hw.services[0].len = 40;
        check(hasProblem(validateHardware(hw), true, "1..32"), "payload longer than the result slot");
        HwService other;
        other.name = "TEMP";
        other.id = 1;
        hw.services[0].len = 6;
        hw.services.push_back(other);
        check(hasProblem(validateHardware(hw), true, "service id 1 is already used by service GYRO"), "two services with one id");
        check(hasProblem(validateHardware(hw), false, "no payload length declared"), "no declared length is a warning");
    }
    {
        Hardware hw = board();
        HwDevice d = hw.devices[0];
        d.name = "other";
        d.symbol = "DEV_OTHER";
        d.index = 1;
        hw.devices.push_back(d);
        check(hasProblem(validateHardware(hw), true, "I2C address 0x68 is used by another device"), "two devices at one I2C address");
        hw.devices[1].addr = 0x69;
        hw.devices[1].index = 0;
        check(hasProblem(validateHardware(hw), true, "DeviceMap entry 0 is already used"), "two devices at one DeviceMap entry");
        hw.devices[1].index = 8;
        check(hasProblem(validateHardware(hw), true, "index 0..7"), "DeviceMap index 8");
        hw.devices[1].index = -1;
        check(hasProblem(validateHardware(hw), false, "not in the DeviceMap"), "a device without an index is a warning");
        hw.devices[1].addr = 0x80;
        check(hasProblem(validateHardware(hw), true, "7-bit"), "an 8-bit I2C address");
    }
    {
        Hardware hw = board();
        hw.devices[0].keys.push_back({"reg 0x10", "0x1ff"});
        hw.devices[0].keys.push_back({"frobnicate", "1"});
        hw.devices[0].keys.push_back({"nack", "maybe"});
        std::vector<HwProblem> v = validateHardware(hw);
        check(hasProblem(v, true, "not a byte value") && hasProblem(v, true, "unknown device key 'frobnicate'") && hasProblem(v, true, "true or false"), "bad register values, keys and flags of a device");
    }
    {
        Hardware hw = board();
        hw.consts[0].values = {"70000"};
        check(hasProblem(validateHardware(hw), true, "does not fit 16 bits"), "a constant that does not fit");
        hw.consts[0].values.clear();
        check(hasProblem(validateHardware(hw), true, "at least one value"), "a constant without a value");
    }
    {   // what the model checks do not know, the real tools still catch
        Hardware hw = board();
        hw.equs.push_back({"BROKEN", "NO_SUCH_SYMBOL + 1", ""});
        check(errorsIn(validateHardware(hw)) == 0, "(the model check cannot evaluate expressions)");
        std::vector<HwProblem> t = checkHardwareWithTools(hw);
        check(hasProblem(t, true, "the assembler says") && hasProblem(t, true, "NO_SUCH_SYMBOL"), "...but the assembler is run on the generated include and reports it", show(t));
        Hardware env = board();
        HwCsr bad;
        bad.name = "WRONG";
        bad.addr = 0x400;
        bad.kind = "value";
        bad.bind = "no_such_signal";
        env.csrs.push_back(bad);
        check(errorsIn(validateHardware(env)) == 0, "(the model does not know the simulator's signal names)");
        check(hasProblem(checkHardwareWithTools(env), true, "simulator"), "the simulator is run on the generated environment and reports what it rejects");
    }
}

static void t_devmap_only() {
    section("a DeviceMap entry without an environment device");
    Hardware hw;
    std::vector<std::string> errs;
    check(importHardware(".devmap 0, I2C, 0x50, DEV_EEPROM\n.devmap 3, I2C, 0x68, DEV_IMU\n", "[device imu]\naddr = 0x68\ndefault = 0x11\n", hw, errs), "import", join(errs));
    check(hw.devices.size() == 2, "two devices", std::to_string(hw.devices.size()));
    std::string env = generateEnv(hw), inc = generateInc(hw);
    check(env.find("[device imu]") != std::string::npos && env.find("0x50") == std::string::npos, "only the device that has a [device] section is simulated (the simulator keeps NACKing the other, as before)", env);
    check(inc.find(".devmap 0, I2C, 0x50, DEV_EEPROM") != std::string::npos && inc.find(".devmap 3, I2C, 0x68, DEV_IMU") != std::string::npos, "both stay in the DeviceMap, in index order", inc);
    Hardware again;
    std::vector<std::string> e2;
    check(parseHardware(serializeHardware(hw), again, e2) && !again.devices[0].simulated, "'simulated = false' survives the .achw round trip", join(e2));
}

static void t_paths() {
    section("where the generated files go");
    Hardware hw;
    check(hardwareIncludePath("/p/hw/board.achw", hw) == "/p/hw/board.gen.inc" && hardwareEnvPath("/p/hw/board.achw", hw) == "/p/hw/board.gen.env.cfg", "default: next to the description");
    hw.includeFile = "../common/defs.inc";
    hw.envFile = "imu_env.cfg";
    check(hardwareIncludePath("/p/hw/board.achw", hw) == "/p/hw/../common/defs.inc" && hardwareEnvPath("C:\\p\\board.achw", hw) == "C:\\p\\imu_env.cfg", "relative to the description (either kind of separator)");
    hw.includeFile = "/abs/defs.inc";
    check(hardwareIncludePath("/p/board.achw", hw) == "/abs/defs.inc", "absolute names are kept");
    std::string text = serializeHardware(hw);
    Hardware back;
    std::vector<std::string> e;
    check(parseHardware(text, back, e) && back.includeFile == "/abs/defs.inc" && back.envFile == "imu_env.cfg", "include_file / env_file survive the file", join(e));
}

static void t_raw() {
    section("things the designer does not model are kept");
    Hardware hw;
    std::vector<std::string> errs;
    importHardware(".include \"other.inc\"\n.csr A = 0x10\nSOMETHING ELSE\n", "[timing]\nframe_cycles = 450000\n[inject]\nat 100 = nack dev=0 count=1\n[condition main 0xE]\nexpr = poll.ready\n", hw, errs);
    check(hw.rawInc.size() == 2 && hw.rawInc[0] == ".include \"other.inc\"", "unknown assembler lines are kept verbatim");
    check(hw.env.size() == 3, "[timing], [inject], [condition] are passed through");
    std::string env = generateEnv(hw);
    check(env.find("frame_cycles = 450000") != std::string::npos && env.find("at 100 = nack dev=0 count=1") != std::string::npos && env.find("expr = poll.ready") != std::string::npos, "...and written out again", env);
    check(generateInc(hw).find(".include \"other.inc\"") != std::string::npos, "...also the raw lines");
}

int main() {
    std::printf("AssemblyCore hardware description tests\n");
    t_format();
    t_generate();
    t_import();
    t_validate();
    t_devmap_only();
    t_paths();
    t_raw();
    std::printf("\n%s  %d passed, %d failed\n", g_fail ? "FAILED" : "OK    ", g_pass, g_fail);
    return g_fail ? 1 : 0;
}
